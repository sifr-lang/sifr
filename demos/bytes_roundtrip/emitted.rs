fn main() {
    let payload: Vec<u8> = vec![
        98u8, 105u8, 110u8, 97u8, 114u8, 121u8, 45u8, 115u8, 97u8, 109u8, 112u8, 108u8,
        101u8
    ];
    assert!(payload.starts_with(& vec![98u8, 105u8, 110u8, 97u8, 114u8, 121u8]));
    assert!(payload.ends_with(& vec![115u8, 97u8, 109u8, 112u8, 108u8, 101u8]));
    let mut conversion_ok: bool = false;
    let __sifr_try_res: Result<(), ParseError> = (|| {
        let as_hex: String = {
            let __bytes_receiver = &payload;
            let mut __hex = String::with_capacity(
                __bytes_receiver.len().saturating_mul(2_usize),
            );
            for __byte in __bytes_receiver.iter() {
                __hex.push_str(&format!("{:02x}", * __byte));
            }
            __hex
        };
        let restored: Vec<u8> = ({
            let s: String = as_hex.to_string();
            let mut cleaned = String::new();
            for ch in s.chars() {
                if ch.is_ascii_whitespace() {
                    continue;
                }
                if !ch.is_ascii_hexdigit() {
                    return Err(ParseError {
                        message: format!("invalid hex character: {}", ch),
                    });
                }
                cleaned.push(ch);
            }
            if (cleaned.len() % 2) != 0 {
                return Err(ParseError {
                    message: "fromhex() arg must contain an even number of hexadecimal digits"
                        .to_string()
                        .to_string(),
                });
            }
            let mut result = Vec::new();
            for pair in cleaned.as_bytes().chunks(2) {
                let pair_str = ::std::str::from_utf8(pair)
                    .map_err(|e| ParseError {
                        message: e.to_string(),
                    })?;
                result
                    .push(
                        u8::from_str_radix(pair_str, 16)
                            .map_err(|e| ParseError {
                                message: e.to_string(),
                            })?,
                    );
            }
            Ok::<Vec<u8>, ParseError>(result)
        })?;
        let text: String = ::sifr_runtime::encoding::decode_text(
                &restored,
                &"utf-8".to_string(),
                &"strict".to_string(),
            )
            .map_err(|__message| ParseError { message: __message })?;
        conversion_ok = (text == "binary-sample");
        Ok(())
    })();
    if let Err(__sifr_try_err) = __sifr_try_res {
        let e = __sifr_try_err.clone();
        let _ = format!("{}", e.message.clone());
    }
    assert!(conversion_ok);
}
