fn manifest(name: &str, suffix: &str) -> String {
    format!(
        "[package]\nname = \"{name}\"\nedition = \"2026\"\nsifr-version = \">=0.3,<0.4\"\n\n[source]\nroot = \"src\"\n{suffix}"
    )
}

fn run(cwd: &Path, args: &[&str]) -> std::process::Output {
    Command::new(env!("CARGO_BIN_EXE_sifr"))
        .args(args)
        .current_dir(cwd)
        .output()
        .expect("sifr command should run")
}

fn stderr(output: &std::process::Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

fn snapshot(root: &Path) -> BTreeMap<String, Vec<u8>> {
    let mut files = BTreeMap::new();
    collect_snapshot(root, root, &mut files);
    files
}

fn collect_snapshot(root: &Path, current: &Path, files: &mut BTreeMap<String, Vec<u8>>) {
    let mut entries = std::fs::read_dir(current)
        .expect("snapshot directory should be readable")
        .map(|entry| entry.expect("snapshot entry should be readable"))
        .collect::<Vec<_>>();
    entries.sort_by_key(std::fs::DirEntry::file_name);
    for entry in entries {
        let path = entry.path();
        let metadata = std::fs::symlink_metadata(&path).expect("snapshot metadata should exist");
        if metadata.file_type().is_symlink() {
            files.insert(
                path.strip_prefix(root)
                    .expect("snapshot path should be relative")
                    .display()
                    .to_string(),
                std::fs::read_link(&path)
                    .expect("symlink target should be readable")
                    .as_os_str()
                    .as_encoded_bytes()
                    .to_vec(),
            );
        } else if metadata.is_dir() {
            collect_snapshot(root, &path, files);
        } else {
            files.insert(
                path.strip_prefix(root)
                    .expect("snapshot path should be relative")
                    .display()
                    .to_string(),
                std::fs::read(&path).expect("snapshot file should be readable"),
            );
        }
    }
}
