#!/usr/bin/env bash

set -euo pipefail

TARGETS=(
  "aarch64-apple-darwin"
  "x86_64-apple-darwin"
  "x86_64-unknown-linux-gnu"
  "aarch64-unknown-linux-gnu"
)

usage() {
  cat <<'EOF'
Usage: scripts/distribution/generate_version_installer.sh --version <preview> --artifact-dir <dir> --out <path> [options]

Generate an immutable Sifr version installer that embeds artifact names and SHA-256 checksums.

Options:
  --version <preview>          Semver prerelease version
  --artifact-dir <dir>         Directory containing sifr-<version>-<target>.tar.gz and .sha256 files
  --out <path>                 Output installer path
  --artifact-base-url <url>    Public artifact base URL (default: GitHub release URL for the version)
  --help                       Show this help
EOF
}

VERSION=""
ARTIFACT_DIR=""
OUT=""
ARTIFACT_BASE_URL=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --version)
      VERSION="${2:-}"
      shift 2
      ;;
    --artifact-dir)
      ARTIFACT_DIR="${2:-}"
      shift 2
      ;;
    --out)
      OUT="${2:-}"
      shift 2
      ;;
    --artifact-base-url)
      ARTIFACT_BASE_URL="${2:-}"
      shift 2
      ;;
    --help)
      usage
      exit 0
      ;;
    *)
      echo "unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if [[ -z "${VERSION}" || -z "${ARTIFACT_DIR}" || -z "${OUT}" ]]; then
  echo "--version, --artifact-dir, and --out are required" >&2
  usage >&2
  exit 2
fi

if [[ ! "${VERSION}" =~ ^[0-9]+\.[0-9]+\.[0-9]+-(alpha|beta|rc)\.[0-9]+$ ]]; then
  echo "version must be a semver prerelease using -alpha.N, -beta.N, or -rc.N: ${VERSION}" >&2
  exit 2
fi

if [[ -z "${ARTIFACT_BASE_URL}" ]]; then
  ARTIFACT_BASE_URL="https://github.com/sifr-lang/sifr/releases/download/${VERSION}"
fi

sha256_file() {
  local path="$1"
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "${path}" | awk '{print $1}'
  else
    shasum -a 256 "${path}" | awk '{print $1}'
  fi
}

case_entries=""
for target in "${TARGETS[@]}"; do
  archive_name="sifr-${VERSION}-${target}.tar.gz"
  archive_path="${ARTIFACT_DIR}/${archive_name}"
  checksum_path="${archive_path}.sha256"
  if [[ ! -f "${archive_path}" ]]; then
    echo "artifact missing for target ${target}: ${archive_path}" >&2
    exit 2
  fi
  if [[ ! -f "${checksum_path}" ]]; then
    echo "checksum missing for target ${target}: ${checksum_path}" >&2
    exit 2
  fi
  expected="$(tr -d '[:space:]' <"${checksum_path}")"
  actual="$(sha256_file "${archive_path}")"
  if [[ "${expected}" != "${actual}" ]]; then
    echo "checksum mismatch for ${archive_name}: expected ${expected}, got ${actual}" >&2
    exit 2
  fi
  case_entries="${case_entries}
    ${target})
      archive_name=\"${archive_name}\"
      archive_sha256=\"${expected}\"
      ;;"
done

mkdir -p "$(dirname "${OUT}")"
cat >"${OUT}" <<EOF
#!/usr/bin/env sh
# Generated by scripts/distribution/generate_version_installer.sh. Do not hand-edit.

set -eu

APP_NAME="sifr"
APP_VERSION="${VERSION}"
ARTIFACT_BASE_URL="${ARTIFACT_BASE_URL}"
NO_MODIFY_PATH="\${SIFR_NO_MODIFY_PATH:-0}"

fail() {
  echo "sifr installer: \$*" >&2
  exit 2
}

usage() {
  cat <<'EOFUSAGE'
Usage: sifr-installer.sh [options]

Options:
  --no-modify-path    Do not update shell profiles to add Sifr to PATH
  --help              Show this help

Environment:
  SIFR_INSTALL_DIR        Install directory (default: \$HOME/.sifr/bin)
  SIFR_NO_MODIFY_PATH=1   Do not update shell profiles
  SIFR_TARGET             Override target triple for validation
EOFUSAGE
}

while [ "\$#" -gt 0 ]; do
  case "\$1" in
    --no-modify-path)
      NO_MODIFY_PATH=1
      shift
      ;;
    --help)
      usage
      exit 0
      ;;
    *)
      fail "unknown option: \$1"
      ;;
  esac
done

download() {
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL "\$1" -o "\$2"
  elif command -v wget >/dev/null 2>&1; then
    wget -q -O "\$2" "\$1"
  else
    fail "curl or wget is required to download artifacts"
  fi
}

sha256_file() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "\$1" | awk '{print \$1}'
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "\$1" | awk '{print \$1}'
  else
    fail "sha256sum or shasum is required to verify artifacts"
  fi
}

detect_target() {
  if [ -n "\${SIFR_TARGET:-}" ]; then
    echo "\${SIFR_TARGET}"
    return 0
  fi

  os="\$(uname -s)"
  arch="\$(uname -m)"
  case "\${os}:\${arch}" in
    Darwin:arm64|Darwin:aarch64)
      echo "aarch64-apple-darwin"
      ;;
    Darwin:x86_64)
      echo "x86_64-apple-darwin"
      ;;
    Linux:x86_64)
      echo "x86_64-unknown-linux-gnu"
      ;;
    Linux:aarch64|Linux:arm64)
      echo "aarch64-unknown-linux-gnu"
      ;;
    *)
      fail "unsupported platform: \${os}/\${arch}"
    ;;
  esac
}

profile_path_expr() {
  path="\$1"
  if [ -n "\${HOME:-}" ]; then
    case "\${path}" in
      "\${HOME}/"*)
        suffix="\${path#"\${HOME}/"}"
        printf '\${HOME}/%s\n' "\${suffix}"
        return 0
        ;;
    esac
  fi
  printf '%s\n' "\${path}"
}

write_env_script_sh() {
  install_dir_expr="\$1"
  env_script_path="\$2"
  {
    printf '%s\n' '#!/usr/bin/env sh'
    printf '%s\n' '# Adds Sifr binaries to PATH if needed.'
    printf '%s\n' 'case ":\${PATH}:" in'
    printf '  *:"%s":*)\n' "\${install_dir_expr}"
    printf '%s\n' '    ;;'
    printf '%s\n' '  *)'
    printf '    export PATH="%s:\${PATH}"\n' "\${install_dir_expr}"
    printf '%s\n' '    ;;'
    printf '%s\n' 'esac'
  } >"\${env_script_path}"
}

write_env_script_fish() {
  install_dir_expr="\$1"
  fish_env_script_path="\$2"
  {
    printf 'if not contains "%s" \$PATH\n' "\${install_dir_expr}"
    printf '    set -x PATH "%s" \$PATH\n' "\${install_dir_expr}"
    printf '%s\n' 'end'
  } >"\${fish_env_script_path}"
}

append_source_line() {
  profile_path="\$1"
  source_line="\$2"
  if [ -f "\${profile_path}" ] && grep -F "\${source_line}" "\${profile_path}" >/dev/null 2>&1; then
    return 0
  fi
  {
    [ ! -f "\${profile_path}" ] || printf '\n'
    printf '%s\n' "\${source_line}"
  } >>"\${profile_path}"
  return 1
}

configure_path() {
  [ "\${NO_MODIFY_PATH}" = "1" ] && return 0
  [ -n "\${HOME:-}" ] || return 0

  case ":\${PATH}:" in
    *:"\${install_dir}":*)
      return 0
      ;;
  esac

  sifr_home="\${HOME}/.sifr"
  env_script_path="\${sifr_home}/env"
  fish_config_dir="\${HOME}/.config/fish/conf.d"
  fish_env_script_path="\${fish_config_dir}/sifr.env.fish"
  install_dir_expr="\$(profile_path_expr "\${install_dir}")"
  env_script_expr="\$(profile_path_expr "\${env_script_path}")"
  fish_env_script_expr="\$(profile_path_expr "\${fish_env_script_path}")"
  source_line=". \"\${env_script_expr}\""
  shell_name="\${SHELL##*/}"
  changed=0

  mkdir -p "\${sifr_home}"
  write_env_script_sh "\${install_dir_expr}" "\${env_script_path}"

  if append_source_line "\${HOME}/.profile" "\${source_line}"; then
    :
  else
    changed=1
  fi

  if [ -f "\${HOME}/.bashrc" ] || [ "\${shell_name}" = "bash" ]; then
    if append_source_line "\${HOME}/.bashrc" "\${source_line}"; then :; else changed=1; fi
  fi
  if [ -f "\${HOME}/.bash_profile" ]; then
    if append_source_line "\${HOME}/.bash_profile" "\${source_line}"; then :; else changed=1; fi
  fi

  zsh_home="\${ZDOTDIR:-\${HOME}}"
  if [ -f "\${zsh_home}/.zshrc" ] || [ "\${shell_name}" = "zsh" ]; then
    if append_source_line "\${zsh_home}/.zshrc" "\${source_line}"; then :; else changed=1; fi
  fi

  if [ -d "\${HOME}/.config/fish" ] || [ "\${shell_name}" = "fish" ]; then
    mkdir -p "\${fish_config_dir}"
    write_env_script_fish "\${install_dir_expr}" "\${fish_env_script_path}"
    changed=1
  fi

  if [ "\${changed}" = "1" ]; then
    echo "configured Sifr PATH via \${env_script_path}"
    echo "restart your shell or run: . \"\${env_script_path}\""
    if [ -f "\${fish_env_script_path}" ]; then
      echo "fish users can also run: source \"\${fish_env_script_expr}\""
    fi
  fi
}

target="\$(detect_target)"
archive_name=""
archive_sha256=""

case "\${target}" in${case_entries}
    *)
      fail "unsupported target: \${target}"
      ;;
esac

base_url="\${SIFR_ARTIFACT_BASE_URL:-\${ARTIFACT_BASE_URL}}"
artifact_url="\${base_url%/}/\${archive_name}"
install_dir="\${SIFR_INSTALL_DIR:-}"
if [ -z "\${install_dir}" ]; then
  [ -n "\${HOME:-}" ] || fail "HOME or SIFR_INSTALL_DIR is required"
  install_dir="\${HOME}/.sifr/bin"
fi

if [ "\${SIFR_INSTALLER_TRACE:-0}" = "1" ]; then
  echo "sifr installer version=\${APP_VERSION} target=\${target} archive=\${archive_name}"
fi

tmp_dir="\$(mktemp -d "\${TMPDIR:-/tmp}/sifr-install.XXXXXX")"
cleanup() {
  rm -rf "\${tmp_dir}"
}
trap cleanup EXIT HUP INT TERM

archive_path="\${tmp_dir}/\${archive_name}"
extract_dir="\${tmp_dir}/extract"
mkdir -p "\${extract_dir}"

download "\${artifact_url}" "\${archive_path}"
actual_sha256="\$(sha256_file "\${archive_path}")"
if [ "\${actual_sha256}" != "\${archive_sha256}" ]; then
  fail "checksum mismatch for \${archive_name}: expected \${archive_sha256}, got \${actual_sha256}"
fi

tar -xzf "\${archive_path}" -C "\${extract_dir}"
if [ ! -f "\${extract_dir}/sifr" ]; then
  fail "artifact \${archive_name} does not contain sifr at archive root"
fi

mkdir -p "\${install_dir}"
tmp_binary="\${install_dir}/.sifr.\$\$.tmp"
cp "\${extract_dir}/sifr" "\${tmp_binary}"
chmod 755 "\${tmp_binary}"
mv "\${tmp_binary}" "\${install_dir}/sifr"

echo "installed sifr \${APP_VERSION} to \${install_dir}/sifr"
configure_path
EOF

chmod 755 "${OUT}"
echo "generated version installer ${OUT}"
